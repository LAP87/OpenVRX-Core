// Digital composite video in (6-bit samples at 40 MS/s, the C5VRX receiver's PARLIO bus),
// the mixer's 53-bit entries out: a drop-in for chan_capture.v on a channel whose source is a
// sample bus instead of a TVP5150 (hub docs/design/2026-10-24/DIGITAL_INGANG.md, task 64).
// Bit-exact counterpart of gateware/model/cvbs_capture_ref.py; the rules are described there.
//   word:   {1'b0, field, line[9:0], idx[8:0], Y1, 80, Y0, 80}
//   marker: {1'b1, field, line[9:0], hf[19:0], bad[3:0], 4'b0, length[11:0], 1'b0}
// Luma only in this step (Cb = Cr = 128): the 1H comb (COMB = 1) adds the previous line's
// sample so that the NTSC subcarrier cancels; colour is task 65.
// `lock` is the line flywheel's lock (task 69): mixer2 uses it as channel B's health in place of
// a TVP status that a sample bus does not have; the model records the same changes (lock_trace).
//
// Timing: the luma path (comb sum, level subtraction, gain multiply, clamp, HF sum) runs in a
// three-stage pipeline; the slicer level and the gain are registered once per line. The entries
// therefore leave two to three clocks after the model's sample, in the model's order: the marker
// of a line waits two clocks for the line's last words.
`default_nettype none
module cvbs_capture #(
    parameter COMB = 1,
    parameter AVG = 8                  // the slicer sees the sum of the last AVG samples (1: the sample itself)
) (
    input  wire        clk,            // the sample clock, 40 MHz
    input  wire        rst,
    input  wire [5:0]  d,              // one composite sample per clock
    output reg         e_valid,
    output reg  [52:0] e_data,
    output wire        line_pulse,     // one pulse per completed active line
    output wire        lock            // the line flywheel is locked to the sync period (task 69)
);
    // ---- parameters shared with the model ----------------------------------------------------
    localparam [15:0] H_NOM = 16'd2542, H_TOL = 16'd128, WIN = 16'd64;
    localparam [11:0] T_EQ = 12'd140, T_BROAD = 12'd600;
    localparam [15:0] ACT_CHECK = 16'd300, ACT_START = 16'd362;
    localparam [15:0] SYNC_LO = 16'd88, SYNC_HI = 16'd120, PORCH_LO = 16'd320, PORCH_HI = 16'd352;
    localparam [4:0]  V_LINES = 5'd16;
    localparam [1:0]  MISS_MAX = 2'd3;
    localparam [9:0]  SYNC_INIT16 = 10'd64, BLANK_INIT16 = 10'd320;   // 4 and 20 codes in 1/16
    // bootstrap (bench 2026-10-27): the slicer sweeps while unlocked until a line has been measured
    localparam [12:0] BOOT_STEP = 13'd5084;                            // 2 * H_NOM samples per code
    localparam [5:0]  BOOT_MIN = 6'd8, BOOT_MAX = 6'd40, BOOT_INIT = 6'd12;

    // ---- gain table: G = round(219 * 256 / (2.5 * d7)) for d7 = 2 (blank - sync) ---------------
    // generated by model/cvbs_capture_ref.py (write_gain_vh); sim/test_cvbs_capture.py checks it
    function [11:0] gain_of(input [6:0] d7);
        begin
            case (d7)
`include "cvbs_gain.vh"
                default: gain_of = 12'd0;
            endcase
        end
    endfunction

    // ---- levels: estimates in 1/16 codes, slicer and gain registered per line ----------------
    reg  [9:0]  sync16, blank16;
    reg  [5:0]  slice_r;
    reg  [11:0] g_r;
    reg  [7:0]  blank2_r;
    // the slicer on the moving sum of the AVG samples before this one (bench 2026-10-27: the C5VRX sync tip's
    // noise moved the first-three-low edge up to 32 samples; the mixer then refused the lengths). The sum is a
    // register: with this sample added in front of the comparison, mix.b_clk missed 75 MHz (70.4).
    localparam SW = 6 + $clog2(AVG + 1);
    reg  [5:0]  win [0:AVG-1];         // the AVG most recent samples before this one, oldest at win_i
    reg  [SW-1:0] win_sum;             // their sum
    reg  [$clog2(AVG + 1)-1:0] win_i;
    wire [SW-1:0] sum_now = win_sum + {{(SW-6){1'b0}}, d} - {{(SW-6){1'b0}}, win[win_i]};
    wire        low = win_sum < ({{(SW-6){1'b0}}, slice_r} * AVG);
    integer     wi;
    always @(posedge clk) begin
        if (rst) begin
            for (wi = 0; wi < AVG; wi = wi + 1) win[wi] <= 6'd0;
            win_sum <= 0; win_i <= 0;
        end else begin
            win[win_i] <= d;
            win_sum <= sum_now;
            win_i <= (win_i == AVG - 1) ? 0 : win_i + 1'b1;
        end
    end

    // ---- pulse detector -----------------------------------------------------------------------
    reg  [1:0]  low_run, high_run;
    reg         in_pulse;
    reg  [11:0] pulse_w;
    wire [1:0]  low_run_n  = low  ? ((low_run  == 2'd3) ? 2'd3 : low_run  + 2'd1) : 2'd0;
    wire [1:0]  high_run_n = !low ? ((high_run == 2'd3) ? 2'd3 : high_run + 2'd1) : 2'd0;
    wire        pedge     = !in_pulse && low_run_n == 2'd3;
    wire        pulse_end = in_pulse && high_run_n == 2'd3;
    wire [11:0] pulse_w_n = pedge ? 12'd3 : (in_pulse && !pulse_end && pulse_w != 12'hFFF) ? pulse_w + 12'd1 : pulse_w;

    // ---- line starts --------------------------------------------------------------------------
    reg         have_start, locked, line_open;
    assign lock = locked;               // registered; changes at most once per line
    reg  [15:0] pos_q, hp;
    reg  [1:0]  miss;
    // this sample's position in the line is pos_q + 1 (pos_c); the pulse began two samples ago, so the period
    // between pulse starts is pos_q - 1, as the model's. Until 2026-10-27 it read pos_q - 2: hp then settled
    // one below the true period while the flywheel stepped hp + 1 (pos_q == pred_hi), which cancelled out
    // until the averaged slicer let the model's hp move too.
    wire [15:0] period  = pos_q - 16'd1;
    // Locked, the line starts at the prediction (the start event comes WIN samples after it, with pos WIN,
    // like a flywheel start): the first edge within WIN of the prediction is accepted, nudges the next
    // prediction by round((edge - prediction) / 16) and carries the period estimate, edge to edge, when the line
    // before had an edge too (bench 2026-10-27: the noisy edges wandered 32 samples, the mixer refused
    // the lengths). Unlocked, lines start at edges as before.
    reg  [15:0] pred_rel;            // the next predicted start, relative to this line's start
    reg         pend_have;           // an edge is accepted for the pending line
    reg  [7:0]  pend_err;            // its offset from the prediction, -WIN..WIN
    reg         pend_eq, pend_broad; // its pulse's class so far
    reg         pend_pulse, cur_pulse;   // the pulse in progress is the pending line's / the current line's
    reg         prev_had_edge;
    reg  [15:0] edge_cnt;            // samples since the last accepted edge's pulse start
    wire        acc_free   = !locked && (!have_start || period >= H_NOM - H_TOL);
    wire        start_edge = pedge && acc_free;
    wire [16:0] err_c      = {1'b0, period} - {1'b0, pred_rel};               // edge minus prediction
    wire        in_win     = ({1'b0, period} + WIN >= {1'b0, pred_rel}) && ({1'b0, period} <= {1'b0, pred_rel} + WIN);
    wire        accept     = pedge && locked && !pend_have && in_win;
    wire        pend_have_c = pend_have || accept;
    wire [7:0]  pend_err_c  = accept ? err_c[7:0] : pend_err;
    wire        pend_pulse_c = pend_pulse || accept;
    wire        start_pred = locked && !start_edge && pos_q == pred_rel + WIN - 16'd1;   // pos_c == pred_rel + WIN
    wire        started    = start_edge || start_pred;
    // a line period locks when the pulse that started the ending line was a real sync (width >= T_EQ):
    // noise crossing the swept slicer makes edges a line apart, not such pulses
    wire        lock_n     = locked ? 1'b1 : (start_edge && have_start && period <= H_NOM + H_TOL && !pulse_was_eq);
    wire [15:0] pos_c      = start_edge ? 16'd2 : start_pred ? WIN : (pos_q == 16'hFFFF) ? pos_q : pos_q + 16'd1;
    // hp follows accepted edges without a dead zone: hp_acc (hp times 64) += edge period - hp, clamped, and
    // hp = round(hp_acc / 64); the locking period seeds both (model HP_SHIFT)
    reg  [21:0] hp_acc;
    wire [15:0] edge_period = edge_cnt - 16'd2;
    wire [16:0] hp_diff  = {1'b0, edge_period} - {1'b0, hp};
    wire [21:0] acc_upd  = hp_acc + {{5{hp_diff[16]}}, hp_diff};
    wire [21:0] acc_clamp = (acc_upd < {H_NOM - H_TOL, 6'd0}) ? {H_NOM - H_TOL, 6'd0}
                          : (acc_upd > {H_NOM + H_TOL, 6'd0}) ? {H_NOM + H_TOL, 6'd0} : acc_upd;
    wire [21:0] acc_round = acc_clamp + 22'd32;
    wire [15:0] hp_clamp = acc_round[21:6];
    wire        hp_now_upd = accept && prev_had_edge;
    wire [15:0] hp_c     = hp_now_upd ? hp_clamp : hp;
    // the nudge of the next prediction: round(err / 16), -4..4 (model PLL_SHIFT)
    wire [8:0]  nud_sum  = {pend_err_c[7], pend_err_c} + 9'd8;
    wire [15:0] nudge    = {{11{nud_sum[8]}}, nud_sum[8:4]};          // sign-extended to the full 16 bits

    // ---- per-line state -----------------------------------------------------------------------
    reg         cur_active, cur_bad, cur_field, cur_line_valid;
    reg  [9:0]  cur_line;
    reg         pulse_was_eq, pulse_was_broad, active_decided;
    reg  [6:0]  acc;                 // luma NCO
    reg  [5:0]  acc_len;             // byte-tick NCO, free running
    reg  [11:0] len_ticks;
    reg  [9:0]  y_count;
    reg  [10:0] sync_sum, porch_sum;
    reg         prev_active;
    reg  [15:0] prev_len;            // the previous line's length: the comb partner exists below it
    // vertical
    reg         field, seen_normal, numbered, vs_seen;
    reg  [4:0]  countdown;
    reg  [9:0]  line_no;

    // the accepted pulse of this line: width classification; of the pending line: class flags only
    wire        class_now   = in_pulse && cur_pulse;
    wire        eq_clear    = class_now && pulse_w_n >= T_EQ;
    wire        broad_now   = class_now && pulse_w_n >= T_BROAD && !pulse_was_broad;
    wire        vsync_now   = broad_now && seen_normal;
    wire        pend_class  = in_pulse && pend_pulse;
    // at the start event the pending pulse becomes the line's, and this sample's width counts for it (the
    // model copies the flags, then classifies)
    wire        eq_at_start    = pend_eq && !(pend_class && pulse_w_n >= T_EQ);
    wire        broad_at_start = pend_class && pulse_w_n >= T_BROAD && !pend_broad;

    // byte ticks (free running)
    wire [6:0]  acc_len_n = {1'b0, acc_len} + 7'd27;           // up to 66: seven bits
    wire        len_tick  = acc_len_n >= 7'd40;
    wire [11:0] len_total = (len_ticks == 12'hFFF) ? len_ticks : len_ticks + {11'd0, len_tick};   // this line including this sample

    // luma NCO
    wire [6:0]  acc_n = acc + 7'd27;
    wire        tick  = acc_n >= 7'd80;

    // ---- 1H comb memory: read [pos] (last line's sample), write [pos - 1] with the previous sample
    reg  [5:0]  mem [0:4095];
    reg  [5:0]  prev_q, s_d1;
    reg  [11:0] wr_addr;
    reg         wr_en;
    always @(posedge clk) begin
        prev_q <= mem[pos_c[11:0] + 12'd1];          // for the next cycle's position
        if (wr_en) mem[wr_addr] <= s_d1;
    end

    // ---- level update at the end of a line (the old line's pos_q and flags) -------------------
    wire        lvl_upd   = started && pos_q >= PORCH_HI && !cur_bad && !pulse_was_eq;
    wire [10:0] sync_m16  = {1'b0, sync_sum[10:1]};      // 32-sample mean in 1/16 codes
    wire [10:0] porch_m16 = {1'b0, porch_sum[10:1]};
    wire [11:0] sync_df   = {1'b0, sync_m16} - {2'b00, sync16};
    wire [11:0] porch_df  = {1'b0, porch_m16} - {2'b00, blank16};
    wire [9:0]  sync_n    = sync16 + {{2{sync_df[11]}}, sync_df[9:2]};
    wire [9:0]  blank_n   = blank16 + {{2{porch_df[11]}}, porch_df[9:2]};
    // the first measured line replaces the bootstrap estimates outright (levels_fresh); a lost lock clears it
    reg         levels_fresh;
    reg  [5:0]  boot_slice;
    reg  [12:0] boot_cnt;
    wire        unlock_now = start_pred && !pend_have_c && miss == MISS_MAX;
    wire        fresh_set  = lvl_upd && !levels_fresh && !pulse_was_broad;
    wire        fresh_nx   = unlock_now ? 1'b0 : (fresh_set ? 1'b1 : levels_fresh);
    wire [9:0]  sync16_nx  = lvl_upd ? (levels_fresh ? sync_n : sync_m16[9:0]) : sync16;
    wire [9:0]  blank16_nx = (lvl_upd && !pulse_was_broad) ? (levels_fresh ? blank_n : porch_m16[9:0]) : blank16;
    wire [5:0]  sync_lvl_nx = sync16_nx[9:4], blank_lvl_nx = blank16_nx[9:4];
    wire        boot_step  = !locked && boot_cnt == BOOT_STEP - 13'd1;
    wire [5:0]  boot_slice_nx = boot_step ? ((boot_slice >= BOOT_MAX) ? BOOT_MIN : boot_slice + 6'd1) : boot_slice;
    wire [6:0]  dlvl_nx   = (blank_lvl_nx > sync_lvl_nx) ? ({1'b0, blank_lvl_nx - sync_lvl_nx} << 1) : 7'd0;

    // ---- luma pipeline ------------------------------------------------------------------------
    // stage 0: the tick and its operands
    wire        use_prev = (COMB != 0) && prev_active && (pos_c < 16'd4096) && (pos_c < prev_len);
    wire [6:0]  c7     = {1'b0, d} + {1'b0, use_prev ? prev_q : d};
    wire        neg0   = {1'b0, c7} < blank2_r;
    wire [7:0]  mag0   = neg0 ? blank2_r - {1'b0, c7} : {1'b0, c7} - blank2_r;
    wire        y_now  = tick && cur_active && pos_c >= ACT_START && y_count < 10'd720;
    // stage 1: operands registered; stage 2: the product; stage 3: value, HF sum, word
    reg         v1, v2, neg1, neg2, f1, f2;
    reg  [7:0]  mag1;
    reg  [19:0] prod2;
    reg  [9:0]  yc1, yc2, l1, l2;
    wire [11:0] q2     = prod2[19:8];
    wire [12:0] y_pos2 = 13'd16 + {1'b0, q2};
    wire [7:0]  y2     = neg2 ? ((q2 >= 12'd15) ? 8'd1 : 8'd16 - q2[7:0]) : ((y_pos2 > 13'd254) ? 8'd254 : y_pos2[7:0]);
    reg  [7:0]  y_prev, y_pend;
    reg         y_prev_ok;
    reg  [19:0] hf;
    wire [7:0]  y_diff = (y2 > y_prev) ? y2 - y_prev : y_prev - y2;
    wire        word_now = v2 && yc2[0];
    wire [52:0] word = {1'b0, f2, l2, yc2[9:1], y2, 8'h80, y_pend, 8'h80};

    // ---- the marker, two clocks after the start so that the line's last words are out --------
    reg  [1:0]  mk_sr;
    reg         mk_field, mk_bad;
    reg  [9:0]  mk_line;
    reg  [11:0] mk_len;
    wire        marker_now = started && cur_line_valid && cur_active;
    wire        marker_out = mk_sr[0];
    wire [52:0] marker = {1'b1, mk_field, mk_line, hf, 3'b000, mk_bad, 4'b0000, mk_len, 1'b0};
    reg         pend;
    reg  [52:0] pend_data;
    assign line_pulse = marker_out;

    always @(posedge clk) begin
        e_valid <= 1'b0;
        // ---- pulse detector ----
        low_run  <= low_run_n;
        high_run <= high_run_n;
        if (pedge) in_pulse <= 1'b1;
        else if (pulse_end) in_pulse <= 1'b0;
        pulse_w <= pulse_w_n;
        if (pulse_end) begin cur_pulse <= 1'b0; pend_pulse <= 1'b0; end
        // ---- accepted edges while locked ----
        edge_cnt <= (edge_cnt == 16'hFFFF) ? edge_cnt : edge_cnt + 16'd1;
        if (accept) begin
            pend_have <= 1'b1; pend_err <= err_c[7:0]; pend_pulse <= 1'b1;
            if (prev_had_edge) begin hp <= hp_clamp; hp_acc <= acc_clamp; end
            edge_cnt <= 16'd3;                       // next clock: 3 samples past this pulse's start
        end
        if (pend_class && pulse_w_n >= T_EQ) pend_eq <= 1'b0;
        if (pend_class && pulse_w_n >= T_BROAD) pend_broad <= 1'b1;

        // ---- free-running byte ticks ----
        acc_len <= len_tick ? acc_len_n[5:0] - 6'd40 : acc_len_n[5:0];

        // ---- comb memory write: the previous sample at the previous position ----
        s_d1    <= d;
        wr_addr <= pos_c[11:0];
        wr_en   <= (line_open || started) && pos_c < 16'd4096;

        // ---- slicer level and gain for the next sample (the levels change only at a start) ----
        slice_r  <= fresh_nx ? (({1'b0, sync_lvl_nx} + {1'b0, blank_lvl_nx}) >> 1) : boot_slice_nx;
        g_r      <= gain_of(dlvl_nx);
        blank2_r <= {1'b0, blank_lvl_nx, 1'b0};
        sync16       <= sync16_nx;               // measured at a start (lvl_upd), else held
        blank16      <= blank16_nx;
        levels_fresh <= fresh_nx;
        boot_slice   <= boot_slice_nx;
        boot_cnt     <= (!locked && !boot_step) ? boot_cnt + 13'd1 : 13'd0;

        if (started) begin
            // ---- the line that ends: marker (delayed) and levels ----
            if (marker_now) begin
                mk_sr <= 2'b10; mk_field <= cur_field; mk_line <= cur_line; mk_bad <= cur_bad; mk_len <= len_total;
            end
            prev_active <= cur_active;
            prev_len    <= line_open ? pos_q : 16'd0;
            // ---- the line that starts ----
            if (start_edge) begin                    // unlocked: at the edge, its pulse is the line's
                miss <= 2'd0;
                cur_pulse <= 1'b1;
                locked <= lock_n; have_start <= 1'b1;
                if (lock_n) begin                    // the next line starts at the prediction; the locking
                    pred_rel <= period; edge_cnt <= 16'd3; prev_had_edge <= 1'b1;   // period seeds hp
                    hp <= period; hp_acc <= {period, 6'd0};
                end
                pulse_was_eq <= 1'b1;                // a real pulse counts as equalizing until T_EQ
                pulse_was_broad <= 1'b0;
            end else begin                           // locked: the start event, with or without an edge
                cur_pulse <= pend_pulse_c;
                pend_pulse <= 1'b0; pend_have <= 1'b0; pend_eq <= 1'b1; pend_broad <= 1'b0;
                prev_had_edge <= pend_have_c;
                if (pend_have_c) miss <= 2'd0;
                else if (miss == MISS_MAX) begin locked <= 1'b0; have_start <= 1'b0; miss <= 2'd0; end
                else miss <= miss + 2'd1;
                pred_rel <= hp_c + (pend_have_c ? nudge : 16'd0);
                pulse_was_eq    <= pend_have_c ? eq_at_start : 1'b0;
                pulse_was_broad <= pend_broad || broad_at_start;
                if (broad_at_start && seen_normal) begin
                    field <= ~field; countdown <= V_LINES; vs_seen <= 1'b1; seen_normal <= 1'b0;
                end
            end
            cur_bad        <= start_pred && !pend_have_c;
            cur_active     <= 1'b0;
            cur_line_valid <= 1'b1;
            line_open      <= 1'b1;
            acc            <= 7'd27;                 // the start sample counts into the new line's NCO
            len_ticks      <= 12'd0;
            y_count        <= 10'd0;
            sync_sum       <= 11'd0;
            porch_sum      <= 11'd0;
            active_decided <= 1'b0;
        end else begin
            len_ticks <= len_total;
            mk_sr <= {1'b0, mk_sr[1]};
            // ---- within the line ----
            if (eq_clear) pulse_was_eq <= 1'b0;
            if (broad_now) pulse_was_broad <= 1'b1;
            if (vsync_now) begin field <= ~field; countdown <= V_LINES; vs_seen <= 1'b1; seen_normal <= 1'b0; end
            if (line_open) begin
                if (pos_c >= SYNC_LO && pos_c < SYNC_HI)   sync_sum  <= sync_sum  + {5'd0, d};
                if (pos_c >= PORCH_LO && pos_c < PORCH_HI) porch_sum <= porch_sum + {5'd0, d};
                if (pos_c == ACT_CHECK && !active_decided) begin
                    active_decided <= 1'b1;
                    if (!low && !pulse_was_eq) seen_normal <= 1'b1;
                    if (vs_seen && countdown != 5'd0) begin
                        countdown <= countdown - 5'd1;
                        if (countdown == 5'd1) begin
                            line_no <= 10'd0; numbered <= 1'b1; cur_active <= 1'b1;
                            cur_line <= 10'd0; cur_field <= field;
                        end
                    end else if (vs_seen && numbered) begin
                        if (!pulse_was_eq && !low) begin
                            cur_active <= 1'b1; line_no <= line_no + 10'd1;
                            cur_line <= line_no + 10'd1; cur_field <= field;
                        end
                    end
                end
                acc <= tick ? acc_n - 7'd80 : acc_n;
                if (y_now) y_count <= y_count + 10'd1;
            end
        end

        // ---- luma pipeline, independent of the start ----
        v1 <= y_now; mag1 <= mag0; neg1 <= neg0; yc1 <= y_count; f1 <= cur_field; l1 <= cur_line;
        v2 <= v1; prod2 <= mag1 * g_r; neg2 <= neg1; yc2 <= yc1; f2 <= f1; l2 <= l1;
        if (v2) begin
            if (y_prev_ok) hf <= hf + {12'd0, y_diff};
            y_prev    <= y2;
            y_prev_ok <= 1'b1;
            if (!yc2[0]) y_pend <= y2;
        end
        if (marker_out) begin                        // the line's words are out: emit, then start the sums anew
            hf <= 20'd0;
            y_prev_ok <= 1'b0;
        end

        // ---- entries ----
        if (word_now) begin
            e_valid <= 1'b1;
            e_data  <= word;
            if (marker_out) begin pend <= 1'b1; pend_data <= marker; end
        end else if (marker_out) begin
            e_valid <= 1'b1;
            e_data  <= marker;
        end else if (pend) begin
            e_valid   <= 1'b1;
            e_data    <= pend_data;
            pend      <= 1'b0;
        end
        pos_q <= (line_open || started) ? pos_c : pos_q;

        if (rst) begin
            line_open <= 1'b0;
            sync16 <= SYNC_INIT16; blank16 <= BLANK_INIT16;
            slice_r <= BOOT_INIT; g_r <= gain_of(7'd32); blank2_r <= 8'd40;
            levels_fresh <= 1'b0; boot_slice <= BOOT_INIT; boot_cnt <= 13'd0;
            low_run <= 2'd0; high_run <= 2'd0; in_pulse <= 1'b0; pulse_w <= 12'd0;
            cur_pulse <= 1'b0; pend_pulse <= 1'b0; pend_have <= 1'b0; pend_err <= 8'd0; pend_eq <= 1'b1;
            pend_broad <= 1'b0; prev_had_edge <= 1'b0; edge_cnt <= 16'd0; pred_rel <= H_NOM;
            have_start <= 1'b0; locked <= 1'b0; pos_q <= 16'd0; hp <= H_NOM; hp_acc <= {H_NOM, 6'd0}; miss <= 2'd0;
            cur_active <= 1'b0; cur_bad <= 1'b0; cur_field <= 1'b0; cur_line <= 10'd0; cur_line_valid <= 1'b0;
            pulse_was_eq <= 1'b1; pulse_was_broad <= 1'b0; active_decided <= 1'b0;
            acc <= 7'd0; acc_len <= 6'd0; len_ticks <= 12'd0; y_count <= 10'd0;
