// NTSC colour demodulation for cvbs_capture.v (task 65), bit-exact counterpart of
// gateware/model/colour_demod_ref.py's ColourDemod: a 32-bit subcarrier NCO locked to the
// burst once per line, the 1H comb for chroma (shared with the luma path in cvbs_capture.v),
// a 32-tap boxcar on the demodulated I/Q, and the ROT/K inverse map of the imperfect 1H comb
// (D_LINE = 172.83 deg, not 180) to Cb/Cr at 4:2:2 (one pair per two luma ticks).
//
// Fed by cvbs_capture.v's own signals, so the sample/position alignment is the capture's:
//   d          the 6-bit sample this clock
//   started    the line-start event this clock (pos_c is 2 or WIN = 64 there, as the model's pos)
//   pos_c      this sample's position in the line
//   use_prev / prev_q  the 1H comb partner (the previous line's sample at this position)
//   blank6     this line's blanking level (blank16[9:4])
//   tick / y_now  the capture's luma NCO tick / an emittable luma tick
// Outputs cb/cr are registered at the even ticks of an active line (the model's ticks % 2 == 0);
// cvbs_capture.v packs them into the word's chroma bytes, which are emitted 3 clocks later, so
// the values are stable when the word leaves.
//
// Unsigned vectors only, sign carried in the MSB (Apicula miscompiles signed compares; see
// ycbcr2rgb.v): signed operands are un-biased (tables hold value+128), multiplied as magnitudes,
// and negated as two's complement; every "arithmetic" shift is a sign-extended bit slice, which
// is exact floor division in two's complement. The includes colour_luts_*.vh are generated by
// model/colour_demod_ref.py (lut_vh) and checked by sim/test_colour_demod_rtl.py.
//
// K (CHROMA_K, 12-bit two's complement) calibrates full-scale chroma to +-111 codes:
// model chroma_k(white-blank) = -1025 (12'hBFF) for white-blank = 40 (levels 4/22/62),
// -1322 (12'hAD6) for 31 (C5VRX levels 23/31/62). On the bench this should come from the
// measured burst amplitude instead.
`default_nettype none
module colour_demod #(
    parameter COMB = 1,
    parameter [11:0] CHROMA_K = 12'hBFF       // -1025, two's complement; chroma_k(40)
) (
    input  wire        clk,
    input  wire        rst,
    input  wire [5:0]  d,
    input  wire        started,
    input  wire        line_open,
    input  wire [15:0] pos_c,
    input  wire        use_prev,
    input  wire [5:0]  prev_q,
    input  wire [5:0]  blank6,
    input  wire        tick,
    input  wire        y_now,
    output reg  [7:0]  cb,
    output reg  [7:0]  cr
);
    // ---- constants from the model (colour_demod_ref.py) --------------------------------------
    localparam [31:0] FSC_INC   = 32'd384350718;    // round(2^32 * 3579545 / 40e6)
    localparam [20:0] LOOP_GAIN = 21'd1694976;     // 6621*256
    localparam [20:0] INC_CLAMP = 21'd2000000;
    localparam [28:0] INC_LO    = 29'd382350718;   // FSC_INC - INC_CLAMP
    localparam [28:0] INC_HI    = 29'd386350718;   // FSC_INC + INC_CLAMP
    localparam [15:0] BURST_LO  = 16'd202, BURST_HI = 16'd313;
    localparam [6:0]  BURST_MIN = 7'd60;
    localparam [15:0] ACT_START = 16'd362;
    localparam [9:0]  WORDS = 10'd360;
    // ROT_C8 = -8, ROT_S8 = -127 (127*cos/sin of D_LINE/2 = 86.42 deg); the Cb/Cr map below is
    // the exact inverse of the comb/demod axis map (model module header)

    // ---- LUTs ---------------------------------------------------------------------------------
    function [7:0] cos_of(input [7:0] p);
        begin
            case (p)
`include "colour_luts_cos.vh"
                default: cos_of = 8'd128;
            endcase
        end
    endfunction
    function [7:0] sin_of(input [7:0] p);
        begin
            case (p)
`include "colour_luts_sin.vh"
                default: sin_of = 8'd128;
            endcase
        end
    endfunction
    function [15:0] inv_of(input [7:0] m);
        begin
            case (m)
`include "colour_luts_inv.vh"
                default: inv_of = 16'd257;
            endcase
        end
    endfunction

    // ---- signed helpers (unsigned vectors, sign in MSB) ---------------------------------------
    // (a*b + 64) >>> 7 for a 7-bit and an 8-bit (biased by +128) two's-complement operand; 8-bit
    // result. The table value is v = b - 128: its sign is NEGATIVE exactly when b < 128 (b[7] == 0),
    // so the sign bit is ~b[7] and the magnitude is b[7] ? b - 128 : 128 - b. |a*v| <= 63*127
    // < 2^14, so bits [14:7] of the sign-extended sum are the exact floor shift.
    function [7:0] mul_r7(input [6:0] a, input [7:0] b);
        reg        an, bn;
        reg  [6:0] am;
        reg  [7:0] bm;
        reg  [14:0] p, t;
        begin
            an = a[6];  am = an ? -a : a;
            bn = ~b[7]; bm = b[7] ? (b - 8'd128) : (8'd128 - b);  // sign and |b - 128|
            p  = am * bm;
            t = (((an ^ bn) ? -p : p) + 15'd64);
            mul_r7 = t[14:7];
        end
    endfunction
    // signed a (aw bits) times the signed constant k (kw bits): aw+kw-bit two's complement
    function [27:0] smul(input [15:0] a, input [11:0] k);
        reg        an;
        reg  [15:0] am;
        reg  [11:0] km;
        reg  [27:0] p;
        begin
            an = a[15]; am = an ? -a : a;
            km = k[11] ? -k : k;
            p  = am * km;
            smul = (an ^ k[11]) ? -p : p;
        end
    endfunction

    // ---- subcarrier NCO ------------------------------------------------------------------------
    reg  [31:0] phase;
    reg  [28:0] inc, inc_new;
    wire [7:0]  ph8   = phase[31:24];
    wire [7:0]  cos_u = cos_of(ph8);
    wire [7:0]  sin_u = sin_of(ph8);

    // ---- burst window (the model accumulates the window inclusive of the lock sample) ----------
    wire        in_burst  = (pos_c >= BURST_LO) && (pos_c < BURST_HI);
    wire [6:0]  sb        = {1'b0, d} - {1'b0, blank6};            // the sample minus blanking
    wire [7:0]  bi_t      = mul_r7(sb, cos_u);
    wire [7:0]  bq_t      = mul_r7(sb, sin_u);
    reg  [13:0] burst_i, burst_q;
    reg  [6:0]  burst_n;
    wire [13:0] bi_n = burst_i + {6'b0, bi_t};
    wire [13:0] bq_n = burst_q + {6'b0, bq_t};
    wire        lock_now = (pos_c == BURST_HI - 16'd1);
    // mag = |bi_n|+|bq_n|+1 (the accumulated vector including the lock sample, as the model's)
    wire [13:0] bin_m = bi_n[13] ? -bi_n : bi_n;
    wire [13:0] bqn_m = bq_n[13] ? -bq_n : bq_n;
    wire [14:0] mag   = {1'b0, bin_m} + {1'b0, bqn_m} + 15'd1;
    wire        mag_ok = (mag >= BURST_MIN) && burst_n != 7'd0;
    wire [7:0]  m8    = (mag >= 15'd256) ? 8'd255 : mag[7:0];
    // est = clamp((bi_n * inv(m8)) >> 8, -512, 512); 14-bit signed x 16-bit unsigned -> 30-bit
    wire [13:0] bin_abs = bi_n[13] ? -bi_n : bi_n;
    wire [29:0] est_p   = bin_abs * inv_of(m8);
    wire [29:0] est_ps  = bi_n[13] ? -est_p : est_p;
    wire [21:0] est_sh  = {est_ps[29], est_ps[28:8]};              // floor(/256), 22-bit two's complement
    // clamp to [-512, 512]: the 22-bit two's complement est_sh compared by magnitude:
    // positive: value = est_sh[20:0]; negative: magnitude = -est_sh (22-bit) = ~est_sh + 1, whose
    // clamp to [-512, 512] by magnitude: negate the 22-bit two's complement value when negative
    // and compare the low 21 bits (the magnitude) against 512
    wire [21:0] est_abs = est_sh[21] ? -est_sh : est_sh;
    wire        est_big = !est_sh[21] && (est_sh[20:0] > 21'd512);
    wire        est_neg = est_sh[21] && (est_abs[20:0] > 21'd512);
    wire [10:0] est = est_neg ? 11'd512      // two's complement -512
                   : est_big ? 11'd512
                   : est_sh[10:0];
    // err += (est - err) >> 4 (LOOP_SHIFT), 12-bit two's complement
    reg  [11:0] err;
    wire [11:0] err_d  = {est[10], est} - err;
    wire [11:0] err_ds = {{3{err_d[11]}}, err_d[11:4]};
    wire [11:0] err_n  = err + err_ds;
    // inc = clamp(FSC_INC - ((err*LOOP_GAIN) >> 8), INC_LO, INC_HI)
    wire [11:0] errm    = err[11] ? -err : err;
    wire [32:0] gain_p  = errm * LOOP_GAIN;
    wire [32:0] gain_ps = err[11] ? -gain_p : gain_p;
    wire [24:0] q25     = {gain_ps[32], gain_ps[32:8]};            // floor(/256)
    wire [29:0] inc_raw = {1'b0, FSC_INC} - {{5{q25[24]}}, q25};
    wire [28:0] inc_cl  = inc_raw[29] ? INC_LO
                        : (inc_raw[28:0] > INC_HI) ? INC_HI : inc_raw[28:0];

    // ---- chroma front end: comb subtraction, demod, boxcar ------------------------------------
    wire [6:0] csub   = (COMB != 0) ? (use_prev ? ({1'b0, d} - {1'b0, prev_q}) : 7'd0)
                                    : ({1'b0, d} - {1'b0, blank6});
    wire [7:0] i_t = mul_r7(csub, cos_u);
    wire [7:0] q_t = mul_r7(csub, sin_u);
    reg  [12:0] i_sum, q_sum;
    reg  [7:0]  i_win [0:31];
    reg  [7:0]  q_win [0:31];
    reg  [4:0]  win_pos;
    wire [12:0] i_sum_n = i_sum + {5'b0, i_t} - {5'b0, i_win[win_pos]};
    wire [12:0] q_sum_n = q_sum + {5'b0, q_t} - {5'b0, q_win[win_pos]};
    // i_lp = floor(i_sum_n / 32); |i_sum| <= 32*63 = 2016 < 2^11, 8-bit signed result
    wire [7:0] i_lp = {i_sum_n[12], i_sum_n[12:5]};
    wire [7:0] q_lp = {q_sum_n[12], q_sum_n[12:5]};

    // ---- luma-tick counter (the model's self.ticks, reset at every line start) ------------------
    reg  [9:0] tick_cnt;
    // chroma pair at the even ticks of an active line, as the model (ticks % 2 == 0, <= 2*WORDS);
    // y_now is the capture's tick gate (active, pos >= ACT_START, y_count < 720)
    wire chroma_now = y_now && !tick_cnt[0] && (tick_cnt < 2 * WORDS);

    // ---- the ROT/K inverse map ------------------------------------------------------------------
    // Cb = 128 - (i_lp*ROT_C8 + q_lp*ROT_S8)*K >> 14 with ROT_C8 = -8, ROT_S8 = -127:
    //   s1 = -(i_lp<<3) - (q_lp<<7) + q_lp          (16-bit two's complement)
    //   s2 = -(i_lp<<7) + i_lp + (q_lp<<3)
    // then v = (s*K) >> 14 (14-bit slice), Cb = clamp(128 - v, 1, 254)
    wire [15:0] s1 = -({9'b0, i_lp} << 3) - ({8'b0, q_lp} << 7) + {8'b0, q_lp};
    wire [15:0] s2 = -({8'b0, i_lp} << 7) + {8'b0, i_lp} + ({9'b0, q_lp} << 3);
    wire [27:0] p1 = smul(s1, CHROMA_K);
    wire [27:0] p2 = smul(s2, CHROMA_K);
    wire [13:0] v1 = p1[27:14];                                    // floor(/2^14)
    wire [13:0] v2 = p2[27:14];
    wire [12:0] u1 = 13'd128 - {v1[13], v1};
    wire [12:0] u2 = 13'd128 - {v2[13], v2};
    // clamp to 1..254: u >= 0x1000 (negative) -> 1; 0x0FF..0x0FE range check on the value bits
    wire [7:0]  cb_n = u1[12] ? 8'd1 : (u1[11:0] > 12'd254 ? 8'd254 : u1[7:0]);
    wire [7:0]  cr_n = u2[12] ? 8'd1 : (u2[11:0] > 12'd254 ? 8'd254 : u2[7:0]);

    integer wi;
    always @(posedge clk) begin
        if (rst) begin
            phase <= 32'd0; inc <= FSC_INC; inc_new <= FSC_INC; err <= 12'd0;
            burst_i <= 14'd0; burst_q <= 14'd0; burst_n <= 7'd0;
            i_sum <= 13'd0; q_sum <= 13'd0; win_pos <= 5'd0; tick_cnt <= 10'd0;
            cb <= 8'd128; cr <= 8'd128;
            for (wi = 0; wi < 32; wi = wi + 1) begin i_win[wi] <= 8'd0; q_win[wi] <= 8'd0; end
        end else begin
            // NCO: the phase adds inc every sample; the lock sample registers the new increment,
            // which applies from the next sample (the model: inc = inc_new at the end of the
            // lock sample's step)
            phase   <= phase + {3'b0, inc};
            inc     <= (lock_now && mag_ok) ? inc_cl : inc;
            if (started) begin
                burst_i <= 14'd0; burst_q <= 14'd0; burst_n <= 7'd0;
                win_pos <= 5'd0;
                tick_cnt <= 10'd0;
            end else if (line_open) begin
                if (in_burst) begin
                    burst_i <= bi_n; burst_q <= bq_n; burst_n <= burst_n + 7'd1;
                end
                tick_cnt <= tick ? tick_cnt + 10'd1 : tick_cnt;
            end
            if (lock_now && mag_ok) err <= err_n;
            // boxcar running sums (the window position resets at line starts, as the model's;
            // the sums themselves run across lines, as the model's)
            i_sum <= i_sum_n; q_sum <= q_sum_n;
            i_win[win_pos] <= i_t; q_win[win_pos] <= q_t;
            win_pos <= (win_pos == 5'd31) ? 5'd0 : win_pos + 5'd1;
            if (chroma_now) begin
                cb <= cb_n; cr <= cr_n;
            end
        end
    end
endmodule
`default_nettype wire
