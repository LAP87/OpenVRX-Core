"""Analog 5.8 GHz channel table and RX5808 (RTC6715) register values.

Source of truth for rtl/vtx_channels.vh (python gateware/model/vtx_channels.py).
Frequencies and the register formula are the ones in sheaivey/rx5808-pro-diversity
(research/raw/rx5808/channels.cpp, receiver_spi.cpp):

    synth register B (address 0x1) = (N << 7) | A,  N = ((f - 479) / 2) // 32,  A = ((f - 479) / 2) % 32
    (local oscillator 479 MHz below the channel, F_lo = 2 * (N*32 + A) MHz)

SPI frame, LSB first: 4 address bits, 1 write bit (= 1), 20 data bits; data
is taken on the rising clock edge while SEL is low.

Sweden (PTSFS 2025:1): video transmitters may use 5725-5875 MHz at 25 mW.
`in_swe_band` marks those channels so the UI can flag the others.
"""
from pathlib import Path

BANDS = [
    ('A', [5865, 5845, 5825, 5805, 5785, 5765, 5745, 5725]),
    ('B', [5733, 5752, 5771, 5790, 5809, 5828, 5847, 5866]),
    ('E', [5705, 5685, 5665, 5645, 5885, 5905, 5925, 5945]),
    ('F', [5740, 5760, 5780, 5800, 5820, 5840, 5860, 5880]),
    ('R', [5658, 5695, 5732, 5769, 5806, 5843, 5880, 5917]),
    ('L', [5362, 5399, 5436, 5473, 5510, 5547, 5584, 5621]),
]
SPI_ADDR_SYNTH_B = 0x1


def synth_reg(f_mhz):
    flo = (f_mhz - 479) // 2
    return ((flo // 32) << 7) | (flo % 32)


def lo_mhz(reg):
    n, a = reg >> 7, reg & 0x7F
    return 2 * (n * 32 + a)


def in_swe_band(f_mhz):
    return 5725 <= f_mhz <= 5875


def spi_frame(reg, addr=SPI_ADDR_SYNTH_B):
    """The 25 bits in transmission order."""
    bits = [(addr >> i) & 1 for i in range(4)] + [1] + [(reg >> i) & 1 for i in range(20)]
    return bits


def table():
    out = []
    for b, freqs in BANDS:
        for i, f in enumerate(freqs):
            out.append((b, i + 1, f, synth_reg(f), in_swe_band(f)))
    return out


def write_vh(path):
    rows = table()
    lines = ['// generated by gateware/model/vtx_channels.py — do not edit',
             f'localparam VTX_N_CH = {len(rows)};',
             '// {legal_in_sweden, band_letter[7:0], freq_mhz[12:0], synth_reg_b[19:0]}',
             'function [41:0] vtx_channel(input [5:0] idx);',
             '    case (idx)']
    for i, (b, ch, f, reg, ok) in enumerate(rows):
        lines.append(f"        6'd{i}: vtx_channel = {{1'b{int(ok)}, 8'h{ord(b):02x}, 13'd{f}, 20'h{reg:05x}}};   // {b}{ch}")
    lines += ["        default: vtx_channel = 42'd0;", '    endcase', 'endfunction', '']
    Path(path).write_text('\n'.join(lines))


if __name__ == '__main__':
    out = Path(__file__).resolve().parent.parent / 'rtl' / 'vtx_channels.vh'
    write_vh(out)
    for b, ch, f, reg, ok in table():
        assert abs(lo_mhz(reg) + 479 - f) <= 1, (b, ch, f)
    print(f'{len(table())} channels -> {out}')
