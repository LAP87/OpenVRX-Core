def columns(ch):
    rows = GLYPHS.get(ch, GLYPHS[' '])
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    return [sum(1 << y for y in range(7) if rows[y][x] == '#') for x in range(5)]


def write_vh(path):
    lines = ['// generated by gateware/model/font5x7.py — do not edit',
             '// 5 column bytes per glyph, bit 0 = top; {code[6:0], col[2:0]} -> byte',
             'function [7:0] font5x7(input [6:0] code, input [2:0] col);',
             '    case ({code, col})']
    for ch in sorted(GLYPHS, key=ord):
        for x, b in enumerate(columns(ch)):
            if b:
                lines.append(f"        {{7'd{ord(ch)}, 3'd{x}}}: font5x7 = 8'h{b:02x};")
    lines += ["        default: font5x7 = 8'h00;", '    endcase', 'endfunction', '']
    Path(path).write_text('\n'.join(lines))


def render_text(page_bytes):
    """Inverse for tests: 128 column bytes of one page -> 21 characters (~ = no glyph has these
    columns; a double-size row decodes through model/oled_ref.py)."""
    lookup = {tuple(columns(c)): c for c in GLYPHS}
    out = []
    for i in range(21):
        cols = tuple(page_bytes[6 * i:6 * i + 5])
        out.append(lookup.get(cols, '~'))
    return ''.join(out)


