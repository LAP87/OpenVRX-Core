    out = Path(__file__).resolve().parent.parent / 'rtl' / 'font5x7.vh'
    write_vh(out)
    assert len({tuple(columns(c)) for c in GLYPHS}) == len(GLYPHS), 'two glyphs are identical'
    print(f'{len(GLYPHS)} glyphs -> {out}')
